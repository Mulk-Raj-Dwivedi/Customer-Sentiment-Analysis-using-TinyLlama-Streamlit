async def run_detailed_extraction(
    screening_results: list[dict], config: dict, output_path: str
) -> dict[str, list[dict]]:
    """Run conditional detailed extraction based on screening flags.

    Evaluates the ``initial_screening`` step's ``next_steps`` routing
    rules against each screening result, dispatches matching transcripts
    to the appropriate ``voc_structured_extraction`` or
    ``voc_list_extraction`` step, and saves results by category.

    Args:
        screening_results: List of screening result dicts from
            ``run_initial_screening``.
        config: VOC pipeline config dict containing ``steps``,
            ``parameters``, ``input.transcript_path``, and ``_rate_limits``.
        output_path: Base directory for saving per-category extraction
            JSON files.

    Returns:
        Dict mapping category names (step names) to lists of result dicts.
        Returns an empty dict when no ``initial_screening`` step is found.
    """
    steps = config.get("steps", [])
    initial_step = next((s for s in steps if s.get("name") == "initial_screening"), None)

    if not initial_step:
        return {}

    # Build map of step names to configs
    step_map = {step["name"]: step for step in steps}

    # Pre-load transcript URI mapping using helper
    transcript_uri_map = _build_transcript_uri_map(config)

    # Collect all extraction tasks
    tasks, task_metadata = _collect_extraction_tasks(
        screening_results, initial_step, step_map, transcript_uri_map, config
    )

    log_echo(f"Running {len(tasks)} detailed extraction tasks...")

    # Execute all tasks in parallel
    results = await asyncio.gather(*tasks, return_exceptions=True)

    # Process and organize results using helper
    detailed_by_category = _process_extraction_results(results, task_metadata)

    # Log summary
    total_items = sum(len(items) for items in detailed_by_category.values())
    log_echo(f"Extracted {total_items} detailed items across {len(detailed_by_category)} categories")

    # Save raw detailed results using helper
    _save_detailed_results(detailed_by_category, output_path)

    return detailed_by_category


async def _run_detailed_step(transcript_uri: str, step_config: dict, global_config: dict) -> list[dict] | dict | None:
    """Run a single detailed extraction step on one transcript.

    Instantiates the appropriate extension
    (``VocStructuredExtractionExtension`` or ``VocListExtractionExtension``)
    from the step config, acquires a rate-limited LLM, and runs extraction.

    Args:
        transcript_uri: Full URI/path to the transcript JSON file.
        step_config: Step-level config dict with ``name``, ``type``,
            ``fields_config``, ``language_model``, and ``parameters``.
        global_config: Global VOC pipeline config providing
            ``DEFAULT_LANGUAGE_MODEL``, ``parameters``, and ``_rate_limits``.

    Returns:
        A dict (for structured extraction), a list of dicts (for list
        extraction), or ``None`` when extraction fails or finds no
        relevant information.

    Raises:
        ValueError: If ``step_config["type"]`` is not a recognized
            extraction type.
    """
    step_type = step_config.get("type")
    step_name = step_config.get("name")

    # Load transcript using the full URI
    artifact_manager = ArtifactManager()
    transcript_data = artifact_manager.read_json(transcript_uri)

    # Extract filename from URI for metadata
    filename = transcript_uri.split("/")[-1]

    # Extract text using helper
    transcript_text = _extract_transcript_text(transcript_data)

    # Resolve parameters
    parameters = step_config.get("parameters", {})
    resolved_parameters = _resolve_parameters(parameters, global_config.get("parameters", {}))

    # Get language model with rate limiting
    default_language_model = global_config.get("DEFAULT_LANGUAGE_MODEL", "gpt-5-mini")
    model_name = step_config.get("language_model", default_language_model)
    rate_limits = global_config.get("_rate_limits")
    models_dict = get_language_models(models={model_name}, rate_limits=rate_limits)
    llm = models_dict[model_name]

    # Create context
    context = ExtractionPipelineRunResultConfig(
        text=transcript_text,
        metadata={"filename": filename},
        responses=[],
    )

    # Validate step_type before try block
    if step_type not in ("voc_structured_extraction", "voc_list_extraction"):
        raise ValueError(f"Unknown step type: {step_type}")

    try:
        if step_type == "voc_structured_extraction":
            step_obj = VocStructuredExtractionConfig(
                name=step_name,
                type=step_type,
                language_model=model_name,
                fields_config=step_config["fields_config"],
                parameters=resolved_parameters,
            )
            extension = VocStructuredExtractionExtension(pipeline_step=step_obj)
            result = await extension.run(context=context, llm=llm)
            return _parse_structured_result(result.answer)

        if step_type == "voc_list_extraction":
            step_obj = VocListExtractionConfig(
                name=step_name,
                type=step_type,
                language_model=model_name,
                fields_config=step_config["fields_config"],
                parameters=resolved_parameters,
                max_items=step_config.get("max_items", 10),
            )
            extension = VocListExtractionExtension(pipeline_step=step_obj)
            result = await extension.run(context=context, llm=llm)
            return result.answer if isinstance(result.answer, list) else [result.answer]

    except Exception as e:
        logger.exception("Detailed extraction failed for %s in %s", step_name, filename)
        # Log validation errors or extraction failures
        # Return None to indicate no information was found
        error_msg = str(e)
        if "validation error" in error_msg.lower():
            logger.info(f"No relevant information found for {step_name} in {filename}")
        else:
            logger.warning(f"Error in detailed extraction for {step_name} in {filename}: {e}")
        return None


def combine_voc_results(
    screening_results: list[dict],
    detailed_results: dict[str, list[dict]],
    transformation_config: dict,
    artifact_manager: ArtifactManager,
) -> pd.DataFrame:
    """Combine screening and detailed results into a final aggregated table.

    Converts results to DataFrames and delegates to ``VocTableCombiner``
    which applies field mappings, derived columns, aggregation rules, and
    final column ordering.

    Args:
        screening_results: List of screening result dicts (one per
            transcript).
        detailed_results: Dict mapping category names to lists of detailed
            extraction result dicts.
        transformation_config: Dict containing paths to ``field_mappings``,
            ``aggregation_rules``, and ``final_columns`` YAML files.
        artifact_manager: ``ArtifactManager`` instance (unused directly but
            required by ``VocTableCombiner``).

    Returns:
        Combined DataFrame with the final schema as defined by
        ``final_columns.yml``.
    """
    # Load transformation configs
    field_mappings_path = transformation_config.get("field_mappings")
    aggregation_rules_path = transformation_config.get("aggregation_rules")
    final_columns_path = transformation_config.get("final_columns")

    # Create VocTableCombiner
    combiner = VocTableCombiner(
        field_mappings_path=field_mappings_path,
        aggregation_rules_path=aggregation_rules_path,
        final_columns_path=final_columns_path,
    )

    # Convert to DataFrames
    df_screening = pd.DataFrame(screening_results) if screening_results else pd.DataFrame()

    detailed_dfs = {}
    for category, items in detailed_results.items():
        if items:
            detailed_dfs[category] = pd.DataFrame(items)
            log_echo(f"  Category '{category}': {len(items)} items, columns: {list(detailed_dfs[category].columns)}")

    log_echo(f"Combining {len(df_screening)} screening records with {len(detailed_dfs)} detail categories...")

    # Run combination
    combined_df = combiner.combine_tables(
        df_full=df_screening,
        detailed_dfs=detailed_dfs,
    )

    log_echo(f"Combined table: {len(combined_df)} rows × {len(combined_df.columns)} columns")

    return combined_df


